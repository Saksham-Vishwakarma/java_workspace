public class operator {

    static void main() {
        int a = 10;

        a = a + 10;
        System.out.println("a =  " + a );
        a = a - 10;
        System.out.println("a =  " + a );
        a = a * 10;
        System.out.println("a =  " + a );
        a = a / 10;
        System.out.println("a =  " + a );
        a = a % 10;
        System.out.println("a =  " + a );
        a++;
        System.out.println("a =  " + a );
        a--;
        System.out.println("a =  " + a );
    }
}
