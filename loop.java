public class loop {
    static void main() {
        // for
        for (int i = 0; i <= 10; i++)
        {
            System.out.println("for(i) : " + i);
        }
        int i = 0;
        while(i <= 10)
        {
            System.out.println("while(i) : " +  i);
            i++;
        }

    }
}
